#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { htmlText } from '../features/courses/csi247/study-guides/html-text.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(process.argv[2] || '');
if (!process.argv[2]) {
  throw new Error('Pass the author-supplied standalone index.html as the first argument.');
}

const html = await readFile(source, 'utf8');
const style = html.match(/<style>([\s\S]*?)<\/style>/i)?.[1];
if (!style) throw new Error('The reference does not contain an inline style block.');

const sections = {};
for (const match of html.matchAll(/<section\s+id="([^"]+)"[^>]*>([\s\S]*?)<\/section>/gi)) {
  const [, id, body] = match;
  if (sections[id]) throw new Error(`Duplicate reference section id: ${id}`);
  const headingHtml = body.match(/<h2[^>]*>([\s\S]*?)<\/h2>/i)?.[1] || id;
  const title = htmlText(headingHtml)
    .replace(/\s+/g, ' ')
    .trim();
  sections[id] = { id, title, body };
}

if (Object.keys(sections).length < 100) {
  throw new Error(`Expected the complete reference, found only ${Object.keys(sections).length} sections.`);
}

const sha256 = createHash('sha256').update(html).digest('hex');
const generated = `// Generated by scripts/import-csi247-study-guide-reference.mjs.\n` +
  `// Structural/content reference: author-supplied CSI247 standalone HTML.\n` +
  `// SHA-256: ${sha256}\n` +
  `export const REFERENCE_SHA256 = ${JSON.stringify(sha256)};\n` +
  `export const REFERENCE_SECTIONS = ${JSON.stringify(sections, null, 2)};\n`;

await Promise.all([
  writeFile(join(root, 'features', 'courses', 'csi247', 'study-guides', 'reference-content.mjs'), generated, 'utf8'),
  writeFile(join(root, 'features', 'courses', 'csi247', 'study-guides', 'reference.css'), `${style.trim()}\n`, 'utf8'),
]);

console.log(`Imported ${Object.keys(sections).length} sections from ${source}`);
console.log(`Reference SHA-256: ${sha256}`);
